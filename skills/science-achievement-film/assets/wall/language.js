const wallLanguageKey = 'yingxu.language';
let wallLanguage = 'zh-CN';
try {
  if (localStorage.getItem(wallLanguageKey) === 'en') wallLanguage = 'en';
} catch {}

function trWall(source, ...values) {
  const message = wallLanguage === 'en' && Object.hasOwn(wallEnglish, source) ? wallEnglish[source] : source;
  return message.replace(/\{(\d+)\}/g, (key, index) => index < values.length ? String(values[index]) : key);
}

// Bind only packaged page text. Media names, filenames, and review notes are project data.
const wallLanguageBindings = [];
function bindWallCopy(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    const original = node.nodeValue;
    const key = original.trim();
    if (!Object.hasOwn(wallEnglish, key) || node.parentElement?.closest('script,style,code')) continue;
    wallLanguageBindings.push(() => {
      node.nodeValue = wallLanguage === 'en' ? original.replace(key, () => trWall(key)) : original;
    });
  }
  root.querySelectorAll('[aria-label], [title], [placeholder], [alt]').forEach(node => {
    for (const attribute of ['aria-label', 'title', 'placeholder', 'alt']) {
      const original = node.getAttribute(attribute);
      if (original && Object.hasOwn(wallEnglish, original)) {
        wallLanguageBindings.push(() => node.setAttribute(attribute, trWall(original)));
      }
    }
  });
}

bindWallCopy(document);
document.querySelectorAll('template').forEach(template => bindWallCopy(template.content));
const wallLanguageSwitch = document.querySelector('[data-language-switch]');
function showWallLanguage() {
  document.documentElement.lang = wallLanguage;
  wallLanguageBindings.forEach(render => render());
  const next = wallLanguage === 'en' ? 'zh-CN' : 'en';
  wallLanguageSwitch.lang = next;
  wallLanguageSwitch.textContent = next === 'en' ? 'EN' : '中文';
  wallLanguageSwitch.setAttribute('aria-label', next === 'en' ? 'Switch to English' : '切换到中文');
}

wallLanguageSwitch.addEventListener('click', () => {
  wallLanguage = wallLanguage === 'en' ? 'zh-CN' : 'en';
  try { localStorage.setItem(wallLanguageKey, wallLanguage); } catch {}
  showWallLanguage();
  window.dispatchEvent(new Event('yingxu-language-change'));
});
showWallLanguage();
